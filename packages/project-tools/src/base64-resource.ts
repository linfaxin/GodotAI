import {ProjectToolError} from './errors.js';

const alphabet=new TextEncoder().encode('ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/');

/** Write ASCII directly to the resource buffer: no spread or large binary string. */
export function base64Resource(prefix:string,data:Uint8Array,suffix:string,maxBytes=64*1024*1024):Uint8Array {
 const encoder=new TextEncoder(),before=encoder.encode(prefix),after=encoder.encode(suffix);
 const length=before.byteLength+4*Math.ceil(data.byteLength/3)+after.byteLength;
 if(!Number.isSafeInteger(length)||!Number.isSafeInteger(maxBytes)||maxBytes<0||length>maxBytes)
  throw new ProjectToolError('E_RESOURCE_BUDGET','Encoded resource exceeds the generated byte budget');
 const output=new Uint8Array(length);output.set(before);let at=before.byteLength;
 for(let i=0;i<data.length;i+=3){
  const a=data[i],hasB=i+1<data.length,hasC=i+2<data.length,b=hasB?data[i+1]:0,c=hasC?data[i+2]:0;
  output[at++]=alphabet[a>>2];output[at++]=alphabet[((a&3)<<4)|(b>>4)];
  output[at++]=hasB?alphabet[((b&15)<<2)|(c>>6)]:61;output[at++]=hasC?alphabet[c&63]:61;
 }
 output.set(after,at);return output;
}
