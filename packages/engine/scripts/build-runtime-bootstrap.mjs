import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const packageRoot=fileURLToPath(new URL('../',import.meta.url));
export async function runtimeBootstrapOutputs(root=packageRoot){
 const outputs=new Map(),constants=[];
 for(const mode of ['classic','module']){
  const filename=path.join(root,'dist/browser/pthread/runtime-bootstrap.'+mode+'.js');
  const result=await build({absWorkingDir:root,entryPoints:[path.join(root,'src/browser/pthread/runtime-bootstrap-'+mode+'-entry.ts')],outfile:filename,bundle:true,format:mode==='module'?'esm':'iife',platform:'browser',target:'es2022',minify:true,write:false,sourcemap:false,legalComments:'none'});
  const bytes=result.outputFiles[0].contents,source=new TextDecoder().decode(bytes);
  outputs.set(filename,bytes);
  constants.push('export const PTHREAD_'+mode.toUpperCase()+'_BOOTSTRAP_SOURCE = '+JSON.stringify(source)+';');
  constants.push('export const PTHREAD_'+mode.toUpperCase()+'_BOOTSTRAP_SHA256 = '+JSON.stringify(createHash('sha256').update(bytes).digest('hex'))+';');
 }
 outputs.set(path.join(root,'src/browser/pthread/runtime-bootstrap-source.ts'),new TextEncoder().encode('// Generated by scripts/build-runtime-bootstrap.mjs; verified by the SDK producer proof.\n'+constants.join('\n')+'\n'));
 return outputs;
}
export async function buildRuntimeBootstrap(root=packageRoot){
 const outputs=await runtimeBootstrapOutputs(root);
 for(const [filename,bytes]of outputs){await mkdir(path.dirname(filename),{recursive:true});const current=await readFile(filename).catch(()=>undefined);if(!current||!current.equals(Buffer.from(bytes)))await writeFile(filename,bytes);}
 return outputs;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href)await buildRuntimeBootstrap();
