import assert from 'node:assert/strict';
import {resolve} from 'node:path';

/** Exercise actual controls while a native scene is running. */
export async function verifyWorkbench(page, out) {
  const checks=[];
  const modifier=await page.evaluate(()=>/Macintosh/.test(navigator.userAgent)?'Meta':'Control');
  const pass=name=>checks.push({name,status:'passed'});
  await page.evaluate(()=>{window.__workbenchFrame=document.querySelector('#preview iframe');});
  const sameFrame=async()=>assert(await page.evaluate(()=>window.__workbenchFrame===document.querySelector('#preview iframe')),'Layout changes must preserve the engine browsing context');
  assert.equal(await page.title(),'GodotAI Playground');
  assert.equal(await page.locator('.brand-name').textContent(),'GodotAI Playground');
  assert.equal(await page.locator('.activity-bar,[id^="activity-"]').count(),0);
  assert.equal(await page.locator('#toggle-sidebar,.file-actions').count(),0);
  assert.equal(await page.locator('#source .monaco-editor').count(),1);
  await page.waitForFunction(()=>document.querySelector('#source .view-line')?.querySelectorAll('span[class*="mtk"]').length>1);
  assert.equal((await page.locator('#sidebar').boundingBox()).x,0);
  assert.equal(await page.locator('header #examples-menu').count(),1);
  assert.equal(await page.locator('#sidebar [data-example]').count(),0);
  await page.locator('#examples-menu > summary').focus();await page.keyboard.press('ArrowUp');
  assert.equal(await page.locator('[data-example="errors"]').evaluate(node=>node===document.activeElement),true);
  await page.keyboard.press('Home');
  assert.equal(await page.locator('[data-example="starter"]').evaluate(node=>node===document.activeElement),true);
  await page.keyboard.press('Escape');assert.equal(await page.locator('#examples-menu').getAttribute('open'),null);
  const folder=page.locator('#files .folder[data-path="/src"]');
  await folder.focus();await page.keyboard.press('ArrowLeft');assert.equal(await page.locator('#files .file').first().isVisible(),false);
  await page.keyboard.press('ArrowRight');await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#files [data-path="/src/App.tsx"]').evaluate(node=>node===document.activeElement),true);
  await page.keyboard.press('ArrowLeft');assert.equal(await folder.evaluate(node=>node===document.activeElement),true);
  await page.click('#collapse-folders');await page.fill('#file-search','Counter');assert(await page.locator('#files .file').isVisible());
  await page.fill('#file-search','');assert.equal(await page.locator('#files .file').first().isVisible(),false);await folder.click();
  await page.locator('#settings-section > summary').click();assert(await page.locator('#profile').isVisible());await page.locator('#settings-section > summary').click();
  await page.locator('#dependencies-section > summary').click();assert(await page.locator('#dependencies').isVisible());await page.locator('#dependencies-section > summary').click();
  await page.locator('#project-menu > summary').focus();await page.keyboard.press('ArrowDown');assert(await page.locator('#export').evaluate(node=>node===document.activeElement));
  await page.keyboard.press('Escape');assert(await page.locator('#project-menu > summary').evaluate(node=>node===document.activeElement));
  await sameFrame();pass('brand-header-menu-and-keyboard-explorer-without-activity-rail');
  const initial=await page.locator('#editor-panel').boundingBox();
  const handle=await page.locator('#panel-resizer').boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();await page.mouse.move(handle.x-80,handle.y+handle.height/2,{steps:8});await page.mouse.up();
  assert((await page.locator('#editor-panel').boundingBox()).width<initial.width-45);
  await sameFrame();
  await page.locator('#panel-resizer').focus();await page.keyboard.press('Home');
  await page.click('#focus-preview');
  assert.equal(await page.locator('#editor-panel').isVisible(),false);
  await sameFrame();
  // Keyboard events from the cross-origin canvas need an explicit, validated
  // UI message; they do not bubble to the parent document.
  await page.frameLocator('#preview iframe').locator('canvas').press('Escape');
  await page.waitForFunction(()=>!document.body.classList.contains('preview-focus'));
  await page.click('#focus-preview');
  await page.locator('#project-menu > summary').click();await page.click('#toggle-files');
  // A native frame may delay the click-driven parent layout update.
  await page.locator('#sidebar').waitFor({state:'visible'});
  assert(await page.locator('#sidebar').isVisible());assert(await page.locator('#editor-panel').isVisible());
  await sameFrame();pass('resizing-and-canvas-escape-preserve-native-frame');

  await page.evaluate(()=>playground.editor.focus());await page.keyboard.press('Control+b');
  assert.equal(await page.locator('#sidebar').isVisible(),false);await sameFrame();
  await page.keyboard.press('Control+b');assert.equal(await page.locator('#sidebar').isVisible(),true);
  await page.fill('#file-search','no-such-file');assert.equal(await page.locator('#files .file').count(),0);assert(await page.locator('#no-files').isVisible());
  await page.fill('#file-search','');assert.equal(await page.locator('#files .file').count(),3);
  await page.evaluate(()=>{const e=playground.editor,m=e.getModel(),a=m.getPositionAt(35),b=m.getPositionAt(48);e.setSelection({startLineNumber:a.lineNumber,startColumn:a.column,endLineNumber:b.lineNumber,endColumn:b.column});});
  await page.locator('#files .file').filter({hasText:'model.ts'}).click();
  await page.locator('#files .file').filter({hasText:'App.tsx'}).click();
  await page.locator('#files .file').filter({hasText:'App.tsx'}).click({button:'right'});assert(await page.locator('#delete-file').isDisabled());await page.keyboard.press('Escape');
  assert.equal(await page.locator('#tabs [role="tab"]').count(),3);
  await page.locator('#tabs [role="tab"]').filter({hasText:'Counter.tsx'}).click();
  assert.deepEqual(await page.evaluate(()=>{const e=playground.editor,m=e.getModel(),s=e.getSelection();return[m.getOffsetAt(s.getStartPosition()),m.getOffsetAt(s.getEndPosition())];}),[35,48]);
  await page.getByRole('button',{name:'关闭标签页 App.tsx',exact:true}).click();
  assert.equal(await page.locator('#tabs [role="tab"]').count(),2);
  assert(await page.evaluate(()=>'/src/App.tsx' in playground.exportProject().files));
  await page.locator('#files .file').filter({hasText:'Counter.tsx'}).focus();await page.keyboard.press('Shift+F10');assert(await page.locator('#file-context-menu').isVisible());await page.keyboard.press('Escape');
  const original=await page.evaluate(()=>playground.editor.getValue());
  await page.evaluate(()=>{const e=playground.editor;e.setPosition(e.getModel().getPositionAt(e.getModel().getValueLength()));e.focus();});
  await page.keyboard.insertText('// MONACO_INPUT');assert((await page.evaluate(()=>playground.exportProject().files['/src/Counter.tsx'])).endsWith('// MONACO_INPUT'));
  await page.keyboard.press(modifier+'+z');assert.equal((await page.evaluate(()=>playground.editor.getValue())).includes('MONACO_INPUT'),false);
  for(let i=0;i<3&&(await page.evaluate(()=>playground.editor.getValue()))!==original;i++)await page.keyboard.press(modifier+'+z');
  assert.equal(await page.evaluate(()=>playground.editor.getValue()),original);
  await page.evaluate(()=>{const e=playground.editor,m=e.getModel();e.setPosition(m.getPositionAt(m.getValue().indexOf('React.useState')+12));e.focus();e.trigger('test','editor.action.triggerSuggest',{});});
  await page.locator('#source .suggest-widget.visible').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#source .suggest-widget')?.textContent.includes('useState'));
  await page.keyboard.press('Escape');
  pass('monaco-tsx-highlighting-typing-undo-and-typescript-completion');
  pass('search-tabs-and-cursor-restoration-keep-project-files');

  const oldHeight=(await page.locator('#dock').boundingBox()).height;
  await page.locator('#dock-resizer').focus();await page.keyboard.press('ArrowUp');
  assert((await page.locator('#dock').boundingBox()).height>oldHeight);
  await page.click('#toggle-dock');assert.equal(await page.locator('#console-panel').isVisible(),false);await sameFrame();
  await page.click('#console-tab');assert(await page.locator('#console-panel').isVisible());
  await page.locator('#console-tab').focus();await page.keyboard.press('ArrowLeft');assert.equal(await page.locator('#problems-tab').getAttribute('aria-selected'),'true');
  await page.keyboard.press('ArrowRight');assert.equal(await page.locator('#console-tab').getAttribute('aria-selected'),'true');
  await page.selectOption('#log-filter','error');
  assert(await page.locator('#logs .log-line').evaluateAll(lines=>lines.every(line=>getComputedStyle(line).display==='none'||line.classList.contains('error'))));
  await page.selectOption('#log-filter','all');
  await page.evaluate(()=>{window.__clipboardDescriptor=Object.getOwnPropertyDescriptor(navigator,'clipboard');Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.__copiedLog=text;},write:async items=>{await Promise.all(items.flatMap(item=>item.types.map(type=>item.getType(type).catch(()=>null))));},readText:async()=>'',read:async()=>[]}});});
  await page.click('#copy-log');await page.waitForFunction(()=>typeof window.__copiedLog==='string');
  assert.equal(await page.evaluate(()=>window.__copiedLog),await page.locator('#logs .log-line').evaluateAll(lines=>lines.filter(line=>getComputedStyle(line).display!=='none').map(line=>line.textContent).join('\n')));
  assert((await page.evaluate(()=>window.__copiedLog)).includes('\n'));
  await page.evaluate(()=>{if(window.__clipboardDescriptor)Object.defineProperty(navigator,'clipboard',window.__clipboardDescriptor);else delete navigator.clipboard;delete window.__clipboardDescriptor;delete window.__copiedLog;});
  await page.locator('#dock-resizer').focus();await page.keyboard.press('Home');
  await page.frameLocator('#preview iframe').locator('canvas').click({position:{x:170,y:45}});
  await page.waitForFunction(()=>playground.events.some(event=>event.text?.includes('"text":"Count: 2"')));
  await sameFrame();pass('dock-and-log-filters-preserve-native-input');
  await page.screenshot({path:resolve(out,'workbench-desktop.png'),fullPage:true});

  await page.click('#shortcuts');assert(await page.locator('#shortcuts-dialog').isVisible());await page.keyboard.press('Escape');assert.equal(await page.locator('#shortcuts-dialog').isVisible(),false);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.equal(await page.locator('#sidebar').isVisible(),false);
  await page.click('#open-files');assert(await page.locator('#sidebar').isVisible());
  assert(await page.locator('#workspace').evaluate(node=>node.inert));
  await page.getByRole('button',{name:'文件操作 Counter.tsx',exact:true}).click();assert(await page.locator('#file-context-menu').isVisible());
  assert(await page.locator('#sidebar').isVisible());await page.click('#rename-file');assert(await page.locator('#file-form').isVisible());await page.keyboard.press('Escape');
  await page.locator('#files .file').filter({hasText:'Counter.tsx'}).click();assert.equal(await page.locator('#sidebar').isVisible(),false);
  assert.equal(await page.locator('#workspace').evaluate(node=>node.inert),false);
  await page.click('#focus-preview');assert.equal(await page.locator('#editor-panel').isVisible(),false);await sameFrame();
  const canvas=await page.locator('#preview iframe').boundingBox();assert(canvas.width<=390&&Math.abs(canvas.width/canvas.height-16/9)<.03);
  await page.screenshot({path:resolve(out,'workbench-mobile.png'),fullPage:true});
  await page.click('#focus-preview');
  for(const width of [320,580,768,1024,1512]) {
    await page.setViewportSize({width,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const brand=await page.locator('.brand-name').boundingBox();assert(brand&&brand.width>0);assert(await page.locator('.brand-name b').isVisible());
    const run=await page.locator('#run').boundingBox();assert(run.x+run.width<=width);
  }
  await page.setViewportSize({width:390,height:390});
  await page.waitForFunction(()=>document.getElementById('toggle-dock').getAttribute('aria-expanded')==='false');
  assert((await page.locator('#preview-panel').boundingBox()).height>70);
  await page.click('#examples-menu > summary');const menu=await page.locator('.examples-popover').boundingBox();assert(menu.y+menu.height<=390-24);await page.keyboard.press('Escape');
  await page.setViewportSize({width:844,height:390});
  await page.waitForFunction(()=>document.getElementById('toggle-dock').getAttribute('aria-expanded')==='false');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight));
  assert.equal(await page.locator('#toggle-dock').getAttribute('aria-expanded'),'false');
  await sameFrame();pass('mobile-drawer-focus-and-short-screen-layout');
  await page.setViewportSize({width:1512,height:1040});
  await page.click('#console-tab');
  await page.evaluate(()=>{delete window.__workbenchFrame;});
  return checks;
}
